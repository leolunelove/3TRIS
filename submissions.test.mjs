import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const out = mkdtempSync(join(tmpdir(), '3tris-submit-'));
try {
  execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', '--module', 'commonjs', '--target', 'es2022', '--skipLibCheck', '--outDir', out, 'src/lib/game/submissions.ts']);
  writeFileSync(join(out, 'package.json'), '{"type":"commonjs"}');
  symlinkSync(resolve('node_modules'), join(out, 'node_modules'));
  const require = createRequire(import.meta.url);
  const { useTris } = require(join(out, 'store.js'));
  const { autoSubmitScore, submitScore } = require(join(out, 'submissions.js'));
  const values = new Map();
  globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
  const run = { mode: 'endless', completed: false, score: 200, lines: 0, level: 1, timeMs: 1000, pieces: 12, pps: 12, at: 1, bestCrossMs: null };
  const reset = id => useTris.getState().patch({ rankedRunId: id, submittedRunId: null, submissionStatus: 'idle', submissionMessage: '' });
  let calls = [];
  globalThis.fetch = async (_url, options) => {
    calls.push(JSON.parse(options.body));
    return { ok: true, json: async () => ({ rank: 3, improved: true }) };
  };
  reset('unnamed');
  autoSubmitScore('unnamed', run, Promise.resolve());
  assert.equal(calls.length, 0, 'unnamed players retain manual submission');
  values.set('3tris-nickname-v1', 'Returning Player');
  reset('delayed');
  let ready;
  const ticket = new Promise(resolve => { ready = resolve; });
  autoSubmitScore('delayed', run, ticket);
  const job = submitScore('delayed', run, 'Returning Player');
  assert.equal(calls.length, 0, 'wait for the run ticket');
  assert.equal(useTris.getState().submissionStatus, 'sending');
  ready(); await job;
  assert.equal(calls.length, 1, 'automatic and manual attempts share one request');
  assert.equal(calls[0].nickname, 'Returning Player');
  assert.equal(useTris.getState().submittedRunId, 'delayed');
  await submitScore('delayed', run, 'Returning Player');
  assert.equal(calls.length, 1, 'completed submissions are not repeated');
  reset('old');
  let finish;
  globalThis.fetch = async (_url, options) => { calls.push(JSON.parse(options.body)); await new Promise(resolve => { finish = resolve; }); return { ok: true, json: async () => ({ rank: 2, improved: true }) }; };
  const oldJob = submitScore('old', run, 'Returning Player');
  reset('new'); finish(); await oldJob;
  assert.equal(calls.at(-1).runId, 'old', 'the original run is posted after restart');
  assert.equal(useTris.getState().submissionStatus, 'idle', 'old responses cannot overwrite the new run');
  let attempts = 0;
  globalThis.fetch = async () => { if (++attempts === 1) throw new Error('Offline'); return { ok: true, json: async () => ({ rank: null, improved: false }) }; };
  reset('retry');
  await submitScore('retry', run, 'Returning Player');
  assert.equal(useTris.getState().submissionStatus, 'error');
  await submitScore('retry', run, 'Returning Player');
  assert.equal(attempts, 2);
  assert.equal(useTris.getState().submissionStatus, 'done');
  reset('sprint');
  autoSubmitScore('sprint', { ...run, mode: 'sprint' }, Promise.resolve());
  autoSubmitScore('sprint', { ...run, score: 0 }, Promise.resolve());
  assert.equal(useTris.getState().submissionStatus, 'idle', 'unfinished sprints and zero scores are skipped');
  autoSubmitScore('sprint', { ...run, mode: 'sprint', completed: true }, Promise.resolve());
  await submitScore('sprint', { ...run, mode: 'sprint', completed: true }, 'Returning Player');
  assert.equal(useTris.getState().submissionStatus, 'done', 'completed sprints post automatically');
  console.log('Passed: automatic score posting, delayed tickets, duplicate prevention, restart isolation, retries, and sprint eligibility.');
} finally { rmSync(out, { recursive: true, force: true }); }
